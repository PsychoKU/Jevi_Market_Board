import re, unicodedata
nf = lambda s: unicodedata.normalize('NFKC', s or '').strip()

def period(t):
    m = re.search(r'(\d{4})年(\d{1,2})月期\s*第(\d)四半期', t)
    if m: return f"{m.group(1)}년 {int(m.group(2))}월기 {m.group(3)}분기" + ("(중간)" if '中間期' in t else '')
    m = re.search(r'(\d{4})年(\d{1,2})月期', t)
    if m: return f"{m.group(1)}년 {int(m.group(2))}월기"
    m = re.search(r'(\d{4})年度\s*第(\d)四半期', t)
    if m: return f"{m.group(1)}년도 {m.group(2)}분기"
    return ''

