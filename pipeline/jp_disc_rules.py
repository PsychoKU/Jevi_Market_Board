def translate(title):
    t = nf(title)
    for pat, tpl, cat, flag in RULES:
        if re.search(pat, t):
            if tpl == '(정정) {orig}':
                inner = re.sub(r'^\(訂正[^)]*\)\s*', '', t).strip('「」 ')
                k, c2, _ = translate(inner) if inner != t else (t, '정정', 0)
                return ('(정정) ' + k, '정정', 0)
            p = period(t)
            return (tpl.replace('{p} ', (p + ' ') if p else '').replace('{p}', p).strip(), cat, flag)
    return (t, '기타', 0)

